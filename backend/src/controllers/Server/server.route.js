const express = require('express');
const auth = require('../../middlewares/auth');
const controller = require('./server.controller');
const router = express.Router();
router.get('/discover', controller.listPublic);
router.get('/mine', auth(), controller.mine);
router.get('/favorites', auth(), controller.listFavorites);
router.post('/:serverId/favorite', auth(), controller.toggleFavorite);
router.post('/', auth(), controller.create);
router.post('/join', auth(), controller.join);
router.post('/:serverId/join', auth(), controller.joinPublic);
router.get('/:serverId/roles', auth(), controller.getRoles);
router.get('/:serverId/join-requests', auth(), controller.listJoinRequests);
router.patch('/:serverId/join-requests/:userId', auth(), controller.reviewJoinRequest);
router.post('/:serverId/roles', auth(), controller.createRole);
router.patch('/:serverId/roles/:roleId', auth(), controller.updateRole);
router.patch('/:serverId/roles/:roleId/members', auth(), controller.updateRoleMember);
router.delete('/:serverId/roles/:roleId', auth(), controller.deleteRole);
router.patch('/:serverId/settings', auth(), controller.updateSettings);
router.get('/:serverId/events', auth(), controller.listEvents);
router.post('/:serverId/events', auth(), controller.createEvent);
router.post('/:serverId/events/:eventId/rsvp', auth(), controller.toggleEventAttendance);
router.get('/:serverId/audit-log', auth(), controller.listAuditLog);
router.get('/:serverId', auth(), controller.getOne);
router.post('/:serverId/channels', auth(), controller.createChannel);
router.get('/:serverId/channels/:channelId/messages', auth(), controller.listMessages);
router.post('/:serverId/channels/:channelId/messages', auth(), controller.sendMessage);
module.exports = router;
